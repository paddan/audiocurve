//! Writes `report.json` (flat, rounded) and `report.md` (one table per audiogram).

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::Path;

/// Metric-name prefixes for which a larger value is worse (checked by the regression test).
pub const LOWER_IS_BETTER: &[&str] = &["thdn_", "imd_", "gainmod_hf", "safety_", "isp_over_db"];

/// Report-only metrics: never checked by the regression test.
pub const REPORT_ONLY: &[&str] = &["safety_output_gain_db", "tilt_db_per_oct", "lowhigh_diff_db"];

fn round2(v: f64) -> f64 {
    (v * 100.0).round() / 100.0
}

pub fn write(map: &BTreeMap<String, f64>, dir: &Path) {
    std::fs::create_dir_all(dir).unwrap();
    let rounded: BTreeMap<&String, f64> = map.iter().map(|(k, v)| (k, round2(*v))).collect();
    let mut json = serde_json::to_string_pretty(&rounded).unwrap();
    json.push('\n');
    std::fs::write(dir.join("report.json"), json).unwrap();
    std::fs::write(dir.join("report.md"), markdown(map)).unwrap();
}

fn markdown(map: &BTreeMap<String, f64>) -> String {
    let mut s = String::from("# Measurement report\n\nGenerated by `cargo run --release --example measure`.\n");
    for aud in ["mild", "steep"] {
        let mut metrics: Vec<&str> = map
            .keys()
            .filter_map(|k| k.strip_prefix(aud).and_then(|r| r.strip_prefix('/')))
            .filter_map(|r| r.split_once('/').map(|(_, m)| m))
            .collect();
        metrics.sort();
        metrics.dedup();
        let _ = write!(s, "\n## {aud}\n\n| metric | speech | music | auto |\n|---|---:|---:|---:|\n");
        for m in metrics {
            let cell = |mode: &str| match map.get(&format!("{aud}/{mode}/{m}")) {
                Some(v) => format!("{:.2}", round2(*v)),
                None => "-".to_string(),
            };
            let _ = writeln!(s, "| {m} | {} | {} | {} |", cell("speech"), cell("music"), cell("auto"));
        }
    }
    s
}
