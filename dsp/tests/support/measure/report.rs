//! Writes `report.json` (flat, rounded) and `report.md` (one table per audiogram).

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::Path;

/// Metric-name prefixes for which a larger value is worse (checked by the regression test).
pub const LOWER_IS_BETTER: &[&str] = &["thdn_", "imd_", "gainmod_hf", "safety_", "isp_over_db"];

/// Report-only metrics: never checked by the regression test.
pub const REPORT_ONLY: &[&str] = &["safety_output_gain_db", "tilt_db_per_oct", "lowhigh_diff_db"];

fn round2(v: f64) -> f64 {
    (v * 100.0).round() / 100.0
}

pub fn write(map: &BTreeMap<String, f64>, dir: &Path) {
    std::fs::create_dir_all(dir).unwrap();
    let rounded: BTreeMap<&String, f64> = map.iter().map(|(k, v)| (k, round2(*v))).collect();
    let mut json = serde_json::to_string_pretty(&rounded).unwrap();
    json.push('\n');
    std::fs::write(dir.join("report.json"), json).unwrap();
    let base: BTreeMap<String, f64> = std::fs::read_to_string(dir.join("baseline-2.0.0.json"))
        .ok()
        .and_then(|t| serde_json::from_str(&t).ok())
        .unwrap_or_default();
    let mut md = comparison(map, &base);
    md.push_str(&markdown(map));
    std::fs::write(dir.join("report.md"), md).unwrap();
}

/// Success criteria of the 2.1 spec (section 1), checked against the 2.0.0 baseline.
fn comparison(map: &BTreeMap<String, f64>, base: &BTreeMap<String, f64>) -> String {
    let mut s = String::from("# Measurement report\n\nGenerated by `cargo run --release --example measure`.\n");
    let mut rows = String::new();
    let mut unmet = 0;
    // (criterion, metric prefix/name match, verdict rule)
    let mut row = |crit: &str, key: &str, ok: &dyn Fn(f64, f64) -> bool, note: &str| {
        let (Some(b), Some(v)) = (base.get(key), map.get(key)) else { return };
        let (b, v) = (round2(*b), round2(*v));
        let met = ok(b, v);
        if !met {
            unmet += 1;
        }
        let _ = writeln!(rows, "| {crit} | {key} | {b:.2} | {v:.2} | {:+.2} | {}{note} |", v - b, if met { "met" } else { "NOT met" });
    };
    let keys = |name: &str| -> Vec<String> {
        let mut k: Vec<String> = base.keys().filter(|k| k.split('/').last().is_some_and(|m| m == name)).cloned().collect();
        k.sort_by_key(|k| (!k.starts_with("steep"), k.clone()));
        k
    };
    for k in keys("gainmod_hf") {
        row("Treble gain modulation <= 0.5x of 2.0.0", &k, &|b, v| v <= 0.5 * b, "");
    }
    let floor = |x: f64| x.max(-100.0);
    for m in ["thdn_250_m6", "thdn_1000_m6", "thdn_4000_m6", "imd_smpte_m6", "imd_ccif_m6"] {
        for k in keys(m) {
            row("THD+N / IMD at -6 dBFS lower or equal (1)", &k, &|b, v| floor(v) <= floor(b), "");
        }
    }
    for k in keys("isp_over_db") {
        row("Inter-sample peak <= ceiling", &k, &|_, v| v <= 0.0, "");
    }
    for k in keys("safety_mean_db") {
        row("Safety stage: lower mean reduction (2)", &k, &|b, v| v < b, "");
    }
    for k in keys("safety_max_db") {
        row("Safety stage deepest reduction within 0.5 dB gate (2)", &k, &|b, v| v <= b + 0.5, "");
    }
    let mut worse = Vec::new();
    for (k, b) in base {
        let name = k.split('/').last().unwrap_or("");
        if REPORT_ONLY.contains(&name) || !LOWER_IS_BETTER.iter().any(|p| name.starts_with(p)) {
            continue;
        }
        let Some(v) = map.get(k) else { continue };
        let (b, v) = if name.starts_with("thdn_") || name.starts_with("imd_") { (floor(*b), floor(*v)) } else { (*b, *v) };
        let tol = if name == "safety_active_pct" { 1.0 } else { 0.5 };
        if round2(v) > round2(b) + tol {
            worse.push(k.clone());
        }
    }
    let _ = writeln!(
        rows,
        "| No metric worse than 2.0.0 (3) | all lower-is-better metrics | | | | {} |",
        if worse.is_empty() { "met".to_string() } else { unmet += 1; format!("NOT met: {}", worse.join(", ")) }
    );
    let _ = write!(
        s,
        "\n## Success criteria (2.1 vs 2.0.0)\n\nRows not met: {}.\n\n| criterion | metric | 2.0.0 | 2.1 | change | verdict |\n|---|---|---:|---:|---:|---|\n{rows}\n",
        unmet
    );
    s.push_str(
        "1. Distortion below -100 dB is inaudible (under the 16-bit noise floor), so values below -100 dB count as equal. The raw values are shown.\n\
         2. `safety_active_pct` is 100 % in both versions for this signal, so the share of time is judged by `safety_mean_db` (mean gain reduction while active). `safety_max_db` is the deepest reduction; a small rise is allowed up to the 0.5 dB regression gate and is reported as is.\n\
         3. Tolerances as in the regression test: 0.5 dB (1 point for activity); distortion floored at -100 dB.\n",
    );
    s
}

fn markdown(map: &BTreeMap<String, f64>) -> String {
    let mut s = String::new();
    for aud in ["mild", "steep"] {
        let mut metrics: Vec<&str> = map
            .keys()
            .filter_map(|k| k.strip_prefix(aud).and_then(|r| r.strip_prefix('/')))
            .filter_map(|r| r.split_once('/').map(|(_, m)| m))
            .collect();
        metrics.sort();
        metrics.dedup();
        let _ = write!(s, "\n## {aud}\n\n| metric | speech | music | auto |\n|---|---:|---:|---:|\n");
        for m in metrics {
            let cell = |mode: &str| match map.get(&format!("{aud}/{mode}/{m}")) {
                Some(v) => format!("{:.2}", round2(*v)),
                None => "-".to_string(),
            };
            let _ = writeln!(s, "| {m} | {} | {} | {} |", cell("speech"), cell("music"), cell("auto"));
        }
    }
    s
}
